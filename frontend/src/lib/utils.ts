import { clsx, type ClassValue } from "clsx";
import { twMerge } from "tailwind-merge";

/**
 * Merges Tailwind CSS classes with proper conflict resolution.
 * Uses clsx for conditional logic + tailwind-merge for deduplication.
 */
export function cn(...inputs: ClassValue[]): string {
  return twMerge(clsx(inputs));
}

/**
 * Format a date string or Date to Indonesian locale
 * e.g. "Senin, 27 Juli 2026"
 */
export function formatDateID(date: Date | string, options?: Intl.DateTimeFormatOptions): string {
  const d = typeof date === "string" ? new Date(date) : date;
  return d.toLocaleDateString("id-ID", {
    weekday: "long",
    day: "numeric",
    month: "long",
    year: "numeric",
    ...options,
  });
}

export const formatDateIndonesian = formatDateID;

/**
 * Format time range string
 * e.g. "08:00 – 10:00 WIB"
 */
export function formatTimeRange(start: string, end: string): string {
  return `${start} – ${end} WIB`;
}

/**
 * Format a number with thousand separator (Indonesian locale)
 */
export function formatNumber(num: number): string {
  return num.toLocaleString("id-ID");
}

/**
 * Truncate a string to maxLength, appending "…"
 */
export function truncate(str: string, maxLength: number): string {
  if (str.length <= maxLength) return str;
  return str.slice(0, maxLength).trimEnd() + "…";
}

/**
 * Generate initials from a full name
 * e.g. "Rafli Firdausy" → "RF"
 */
export function getInitials(name: string, max = 2): string {
  return name
    .split(" ")
    .filter(Boolean)
    .slice(0, max)
    .map((w) => w[0].toUpperCase())
    .join("");
}

/**
 * Sleep utility — for mock API delays in development
 */
export function sleep(ms: number): Promise<void> {
  return new Promise((resolve) => setTimeout(resolve, ms));
}

/**
 * Simple client-side ID generator (for mock data only).
 * Production IDs are UUID v7 generated by the backend.
 */
export function generateId(): string {
  return Math.random().toString(36).slice(2) + Date.now().toString(36);
}

function resolveMinioUrl(path: string, base: string): string {
  let cleanPath = path.replace(/^\//, "");
  try {
    const urlObj = new URL(base);
    const pathname = urlObj.pathname.replace(/^\/|\/$/g, "");
    if (pathname && cleanPath.startsWith(pathname + "/")) {
      cleanPath = cleanPath.substring(pathname.length + 1);
    }
  } catch (e) {
    // Ignore URL parse errors
  }
  return `${base.replace(/\/$/, "")}/${cleanPath}`;
}

/**
 * Utility to convert backend/MinIO URLs (or relative storage paths) to client-accessible URLs.
 * Converts direct MinIO/S3 URLs (e.g. s3.purbalinggakab.go.id:9000 or minio:9000)
 * to backend storage proxy URLs (/api/v1/storage/*) for reliable browser loading.
 */
export function getPublicImageUrl(url?: string): string {
  if (!url) return "";
  if (url.startsWith("blob:") || url.startsWith("data:")) return url;

  let cleanPath = url;

  // Handle absolute HTTP/HTTPS URLs from backend or MinIO
  if (cleanPath.startsWith("http://") || cleanPath.startsWith("https://")) {
    try {
      const u = new URL(cleanPath);
      if (
        u.hostname === "localhost" ||
        u.hostname === "127.0.0.1" ||
        u.hostname === "minio" ||
        u.hostname.includes("s3.purbalinggakab.go.id") ||
        u.port === "9000" ||
        u.pathname.includes("/storage/") ||
        u.pathname.startsWith("/e-notulen/") ||
        u.pathname.startsWith("/notulen/") ||
        u.pathname.startsWith("/opd/")
      ) {
        cleanPath = u.pathname;
      } else {
        return url;
      }
    } catch {
      return url;
    }
  }

  // If path already contains /storage/ prefix, extract raw path
  if (cleanPath.includes("/storage/")) {
    cleanPath = cleanPath.split("/storage/")[1] ?? cleanPath;
  }

  cleanPath = cleanPath.replace(/^\//, "");

  let apiBase = process.env.NEXT_PUBLIC_API_URL || "http://localhost:8080/api/v1";

  if (typeof window !== "undefined") {
    const isLocal =
      window.location.hostname === "localhost" ||
      window.location.hostname === "127.0.0.1";
    if (isLocal) {
      if (apiBase.includes("purbalinggakab.go.id")) {
        apiBase = "http://localhost:8080/api/v1";
      }
    } else if (
      window.location.protocol === "https:" ||
      apiBase.includes("api.e-notulen")
    ) {
      apiBase = `${window.location.origin}/api/v1`;
    }
  }

  const encodedPath = cleanPath
    .split("/")
    .map((p) => encodeURIComponent(decodeURIComponent(p)))
    .join("/");

  return `${apiBase.replace(/\/$/, "")}/storage/${encodedPath}`;
}

/**
 * Normalizes a file URL from the backend to an absolute backend storage proxy URL.
 */
export function getFileUrl(url: string | undefined): string {
  if (!url) return "";
  return getPublicImageUrl(url);
}
